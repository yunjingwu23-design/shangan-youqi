import { readFileSync, writeFileSync } from 'node:fs';

const migrations = [
  '202611020001_salary_intelligence.sql',
  '202611020002_salary_reference_privacy.sql',
];
const body = migrations
  .map((name) => `-- ${name}\n${readFileSync(`supabase/migrations/${name}`, 'utf8')}`)
  .join('\n');
// One transaction: the second migration cannot fail after committing the first.
// Re-running fails safely rather than replacing an existing salary schema.
const output = `-- 上岸有期：薪资情报与 Offer 对比，生产一次性升级。
-- 在已有上岸有期数据库的 Supabase SQL Editor，以 postgres 身份运行全文。
-- 无测试数据，无账号初始化，无凭证，不修改现有岗位/简历/面经。
-- 已安装时请先运行末尾的只读检查，不要删除现有表后重装。
-- Generated by node scripts/build-salary-installer.mjs
begin;
select pg_advisory_xact_lock(hashtextextended('shangan.salary.install',0));
do $preflight$
begin
  if current_user not in ('postgres','supabase_admin') then
    raise exception '请在目标 Supabase SQL Editor 选择 postgres 角色运行。';
  end if;
  if to_regclass('public.app_users') is null or to_regclass('public.profiles') is null
    or to_regclass('public.workspace_entries') is null or to_regclass('public.interviews') is null
    or to_regclass('public.admin_memberships') is null
    or to_regprocedure('private.current_user_id()') is null
    or to_regprocedure('private.require_admin(text[])') is null
    or to_regprocedure('public.delete_my_personal_data()') is null then
    raise exception '现有账号、面试或后台迁移不完整。保留现有数据库，先核查缺失的依赖。';
  end if;
  if to_regclass('public.salary_reports') is not null
    or to_regclass('public.personal_offers') is not null then
    raise exception '薪资结构已存在；本事务未改动数据，请先运行末尾的只读检查。';
  end if;
end $preflight$;
${body}
commit;

-- 可独立运行的上线只读检查；全部应为 true。不得在生产运行本地测试夹具。
select
 (select count(*)=8 and bool_and(c.relrowsecurity)
  from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relname in
    ('salary_reports','salary_companies','salary_role_aliases','salary_verifications',
     'salary_moderation_logs','personal_offers','salary_sources','salary_complaints')) as salary_tables_rls_ok,
 to_regprocedure('public.salary_distribution()') is not null as aggregation_ok,
 to_regprocedure('public.salary_review(uuid,integer,text,uuid,text,text,uuid,boolean,text)') is not null as moderation_ok,
 to_regprocedure('public.salary_admin_summary()') is not null as statistics_ok,
 not has_table_privilege('anon','public.salary_reports','select') as anonymous_details_blocked,
 not has_column_privilege('anon','public.salary_sources','authorization_note','select') as licensing_notes_private;
`;
const path = 'supabase/install-salary.sql';
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output)
    throw new Error('Refresh with node scripts/build-salary-installer.mjs');
} else {
  writeFileSync(path, output);
  console.info(`Generated ${path}`);
}
