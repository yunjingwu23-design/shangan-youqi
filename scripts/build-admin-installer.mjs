import { readFileSync, writeFileSync } from 'node:fs';

// Keep the SQL Editor recovery entrypoint derived from the reviewed migrations.
// The historical migrations remain unchanged for existing migration ledgers.
function reusable(sql) {
  return sql
    .replace(/\bcreate table /g, 'create table if not exists ')
    .replace(/\bcreate unique index /g, 'create unique index if not exists ')
    .replace(/\bcreate index /g, 'create index if not exists ')
    .replace(/\bcreate function /g, 'create or replace function ')
    .replace(/\badd column /g, 'add column if not exists ')
    .replace(/\bdrop policy (\w+) on /g, 'drop policy if exists $1 on ')
    .replace(
      /create policy (\w+) on ([\w.]+)/g,
      'drop policy if exists $1 on $2;\ncreate policy $1 on $2'
    )
    .replace(
      /create trigger (\w+)([^;]*?) on ([\w.]+)/g,
      'drop trigger if exists $1 on $3;\ncreate trigger $1$2 on $3'
    );
}

